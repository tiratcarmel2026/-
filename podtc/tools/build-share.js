/* Builds the share pages: e/<id>.html (rich link preview + light player), assets/og/<id>.png (preview picture)
 * and js/share-pages.js (the list the site uses). Run from the podtc folder:  node tools/build-share.js
 * Needs Playwright only for the pictures; pass --no-images to skip them. */
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..'), SITE = 'https://tiratcarmel2026.github.io/-/podtc/';
global.window = {}; ['js/places.js', 'js/art.js'].forEach(f => eval(fs.readFileSync(path.join(root, f), 'utf8')));
const P = window.PODTC_PLACES, CATS = window.PODTC_CATEGORIES, esc = t => String(t || '').replace(/[&<>"]/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));
const page = ep => { const d = `${ep.subtitle}. ${ep.script.replace(/\s+/g, ' ').slice(0, 150)}…`, url = `${SITE}e/${ep.id}.html`, img = `${SITE}assets/og/${ep.id}.png`;
  return `<!DOCTYPE html>
<html lang="he" dir="rtl" data-ep="${ep.id}">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
  <title>${esc(ep.title)} · podtc</title>
  <meta name="description" content="${esc(d)}">
  <link rel="canonical" href="${url}">
  <meta property="og:type" content="music.song">
  <meta property="og:site_name" content="podtc · עיריית טירת כרמל">
  <meta property="og:locale" content="he_IL">
  <meta property="og:title" content="${esc(ep.title)}: ${esc(ep.subtitle)}">
  <meta property="og:description" content="פרק קצר להאזנה · ${esc((CATS[ep.category] || {}).label || 'podtc')} · טירת כרמל מספרת את עצמה">
  <meta property="og:url" content="${url}">
  <meta property="og:image" content="${img}">
  <meta property="og:image:width" content="1200"><meta property="og:image:height" content="630">
  <meta name="twitter:card" content="summary_large_image"><meta name="twitter:image" content="${img}">
  <meta name="theme-color" content="#0B1F47">
  <link rel="icon" href="../assets/icon-192.png" type="image/png">
  <link rel="preconnect" href="https://fonts.googleapis.com"><link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
  <link href="https://fonts.googleapis.com/css2?family=Heebo:wght@400;600;700;800;900&display=swap" rel="stylesheet">
  <link rel="stylesheet" href="../css/listen.css">
  <script type="application/ld+json">${JSON.stringify({ '@context': 'https://schema.org', '@type': 'PodcastEpisode', name: ep.title, description: d, url, image: img, inLanguage: 'he',
    partOfSeries: { '@type': 'PodcastSeries', name: 'podtc · טירת כרמל מספרת את עצמה', url: SITE },
    contentLocation: { '@type': 'Place', name: ep.title, geo: { '@type': 'GeoCoordinates', latitude: ep.lat, longitude: ep.lng } },
    publisher: { '@type': 'GovernmentOrganization', name: 'עיריית טירת כרמל' } }).replace(/</g, '\\u003c')}</script>
</head>
<body>
  <div id="app"><noscript><h1>${esc(ep.title)}</h1><p>${esc(ep.script)}</p></noscript></div>
  <script src="../js/config.js"></script>
  <script src="../js/places.js"></script>
  <script src="../js/content.js"></script>
  <script src="../js/content-apply.js"></script>
  <script src="../js/share-pages.js"></script>
  <script src="../js/art.js"></script>
  <script src="../js/narrator.js"></script>
  <script src="../js/listen.js"></script>
</body>
</html>
`; };
(async () => {
  fs.mkdirSync(path.join(root, 'e'), { recursive: true }); fs.mkdirSync(path.join(root, 'assets/og'), { recursive: true });
  P.forEach(ep => fs.writeFileSync(path.join(root, 'e', ep.id + '.html'), page(ep)));
  fs.writeFileSync(path.join(root, 'js/share-pages.js'), `/* generated by tools/build-share.js */\nwindow.PODTC_SHARE_PAGES = ${JSON.stringify(P.map(p => p.id))};\n`);
  const today = new Date().toISOString().slice(0, 10);
  fs.writeFileSync(path.join(root, 'sitemap.xml'), `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n` +
    [SITE, SITE + 'accessibility.html'].concat(P.map(p => `${SITE}e/${p.id}.html`)).map(u => `  <url><loc>${u}</loc><lastmod>${today}</lastmod></url>`).join('\n') + '\n</urlset>\n');
  console.log('pages:', P.length);
  if (process.argv.includes('--no-images')) return;
  const { chromium } = require('playwright'); const b = await chromium.launch(), pg = await b.newPage({ viewport: { width: 1200, height: 630 } });
  const logo = fs.readFileSync(path.join(root, 'assets/wordmark-white.png')).toString('base64');
  for (const ep of P) {
    await pg.setContent(`<html dir="rtl"><body style="margin:0;width:1200px;height:630px;display:flex;font-family:Arial,sans-serif;background:#0B1F47;color:#fff;overflow:hidden">
      <div style="flex:1;padding:64px 60px;display:flex;flex-direction:column;justify-content:center">
        <img src="data:image/png;base64,${logo}" style="height:54px;width:auto;align-self:flex-start;margin-bottom:38px">
        <div style="color:#06B6E8;font-size:30px;font-weight:700;margin-bottom:10px">${esc((CATS[ep.category] || {}).label || '')} · פרק להאזנה</div>
        <div style="font-size:${ep.title.length > 22 ? 62 : 78}px;font-weight:900;line-height:1.08">${esc(ep.title)}</div>
        <div style="font-size:34px;color:#C6D3E6;margin-top:16px;line-height:1.3">${esc(ep.subtitle)}</div>
        <div style="margin-top:38px;display:flex;align-items:center;gap:18px;font-size:30px;font-weight:700"><span style="width:72px;height:72px;border-radius:50%;background:#06B6E8;display:grid;place-items:center"><svg width="34" height="34" viewBox="0 0 24 24"><path d="M8 5v14l11-7z" fill="#0B1F47"/></svg></span>לחצו להאזנה</div>
      </div>
      <div style="width:530px;height:630px;position:relative;background:linear-gradient(180deg,#5FD3F3,#12306B)"><div style="position:absolute;inset:0">${window.PodArt.svg(ep.category, ep.id).replace('<svg ', '<svg width="530" height="630" ')}</div></div></body></html>`);
    await pg.screenshot({ path: path.join(root, 'assets/og', ep.id + '.png') });
  }
  await b.close(); console.log('images:', P.length);
})();
